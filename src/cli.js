#!/usr/bin/env node
// typed-css-imports generate [--check] [--locals-convention <c>] <file.module.css>...
// Fallback for toolchains without content mapper support (TypeScript < 7.1, or CI without --runExternalCode): writes
// the types the mapper would produce to <name>.module.d.css.ts next to each file, which tsc picks up when
// `allowArbitraryExtensions` is on. --check only reports stale or missing files (exit 1).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { basename } from "node:path";
import { transform } from "./transform.js";

const args = process.argv.slice(2);
const command = args.shift();
let check = false, localsConvention;
const files = [];
while (args.length) {
  const a = args.shift();
  if (a === "--check") check = true;
  else if (a === "--locals-convention") localsConvention = args.shift();
  else files.push(a);
}
if (command !== "generate" || !files.length) {
  console.error("usage: typed-css-imports generate [--check] [--locals-convention <camelCase|camelCaseOnly|dashes|dashesOnly>] <file.module.css>...");
  process.exit(2);
}
let stale = 0;
for (const file of files) {
  const out = file.replace(/\.css$/, ".d.css.ts");
  let text;
  try { text = `// Generated by typed-css-imports from ${basename(file)}. Do not edit.\n${await transform(readFileSync(file, "utf8"), { fileName: file, localsConvention })}`; }
  catch (e) { console.error(`${file}: ${e.message}`); process.exit(1); }
  if (check) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) { console.error(`${out}: out of date (run typed-css-imports generate ${file})`); stale++; }
  } else {
    writeFileSync(out, text);
    console.log(out);
  }
}
process.exit(stale ? 1 : 0);
