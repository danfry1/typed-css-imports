#!/usr/bin/env node
// typed-css-imports generate [--check] [--locals-convention <c>] [--load-path <dir>]... <file.module.css|scss|sass>...
// Fallback for toolchains without content mapper support (TypeScript < 7.1, or CI without --runExternalCode): writes
// the types the mapper would produce to <name>.module.d.css.ts (or .d.scss.ts, .d.sass.ts) next to each file, which
// tsc picks up when `allowArbitraryExtensions` is on. --check only reports stale or missing files (exit 1).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { basename, resolve } from "node:path";
import { transform, type Options } from "./transform.js";

const args = process.argv.slice(2);
const command = args.shift();
const CONVENTIONS = ["camelCase", "camelCaseOnly", "dashes", "dashesOnly"];
let check = false;
let localsConvention: Options["localsConvention"];
const loadPaths: string[] = [];
const files: string[] = [];
while (args.length) {
  const a = args.shift()!;
  if (a === "--check") check = true;
  else if (a === "--locals-convention") {
    const value = args.shift() ?? "";
    if (!CONVENTIONS.includes(value)) { console.error(`--locals-convention must be one of ${CONVENTIONS.join(", ")}`); process.exit(2); }
    localsConvention = value as Options["localsConvention"];
  }
  else if (a === "--load-path") loadPaths.push(args.shift() ?? ".");
  else files.push(a);
}
if (command !== "generate" || !files.length) {
  console.error("usage: typed-css-imports generate [--check] [--locals-convention <camelCase|camelCaseOnly|dashes|dashesOnly>] [--load-path <dir>]... <file.module.css|scss|sass>...");
  process.exit(2);
}
let stale = 0;
for (const file of files) {
  const out = file.replace(/\.(css|scss|sass)$/, ".d.$1.ts");
  let text;
  try { text = `// Generated by typed-css-imports from ${basename(file)}. Do not edit.\n${await transform(readFileSync(file, "utf8"), { fileName: file, localsConvention, sass: { loadPaths: loadPaths.map((p) => resolve(p)) } })}`; }
  catch (e) { console.error(`${file}: ${e instanceof Error ? e.message : e}`); process.exit(1); }
  if (check) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) { console.error(`${out}: out of date (run typed-css-imports generate ${file})`); stale++; }
  } else {
    writeFileSync(out, text);
    console.log(out);
  }
}
process.exit(stale ? 1 : 0);
